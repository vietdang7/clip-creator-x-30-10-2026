export function generateWordTimestampsFromScript(script: string, totalDurationSec = 30, fps = 30): WordTimestamp[] {
  const words = script
    .replace(/\n+/g, ' ')
    .split(/\s+/)
    .filter(Boolean);
  if (words.length === 0) return [];
  const step = totalDurationSec / words.length;
  return words.map((word, idx) => {
    const startSec = Number((idx * step).toFixed(2));
    const endSec = Number(Math.min(totalDurationSec, (idx + 1) * step).toFixed(2));
    return {
      word,
      startSec,
      endSec,
      startFrame: Math.round(startSec * fps) + 1,
      endFrame: Math.max(Math.round(startSec * fps) + 2, Math.round(endSec * fps)),
    };
  });
}

